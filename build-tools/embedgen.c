/* embedgen: turn files into a C source with a lookup table. No external tools needed. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* embed_get() binary-searches the table with strcmp, so the entries must be in strcmp order no matter
 * how the caller lists the files */
static int cmp_path(const void *a, const void *b) { return strcmp(*(char *const *)a, *(char *const *)b); }

int main(int argc, char **argv) {
    if (argc < 2) { fprintf(stderr, "usage: embedgen out.c files...\n"); return 2; }
    qsort(argv + 2, (size_t)(argc - 2), sizeof(char *), cmp_path);
    FILE *out = fopen(argv[1], "w");
    if (!out) { perror(argv[1]); return 1; }
    fprintf(out, "/* generated by embedgen - do not edit */\n#include <stddef.h>\n#include <string.h>\n");
    for (int i = 2; i < argc; i++) {
        FILE *f = fopen(argv[i], "rb");
        if (!f) { perror(argv[i]); return 1; }
        fprintf(out, "static const unsigned char e%d[] = {", i);
        int c; size_t n = 0;
        while ((c = fgetc(f)) != EOF) { if (n) fputc(',', out); if (n % 40 == 0) fputc('\n', out); fprintf(out, "%d", c); n++; }
        fprintf(out, "%s0};\n", n ? "," : "");
        fclose(f);
    }
    fprintf(out, "typedef struct { const char *name; const unsigned char *data; size_t len; } omc_embed_t;\n");
    fprintf(out, "const omc_embed_t omc_embedded[] = {\n");
    for (int i = 2; i < argc; i++) {
        FILE *f = fopen(argv[i], "rb"); fseek(f, 0, SEEK_END); long sz = ftell(f); fclose(f);
        fprintf(out, "  {\"%s\", e%d, %ld},\n", argv[i], i, sz);
    }
    fprintf(out, "  {0, 0, 0}};\nconst size_t omc_embedded_count = %d;\n", argc - 2);
    fclose(out);
    return 0;
}
