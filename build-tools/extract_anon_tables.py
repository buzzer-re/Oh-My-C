#!/usr/bin/env python3
"""Extract the allowlist tables of omp's session anonymizer (`/dump anon`) as C data.

Usage: build-tools/extract_anon_tables.py <omp checkout> > src/session/anon_tables.h

Reads packages/coding-agent/src/session/session-anonymizer.ts (FIELD_RULES, the key/word sets,
TOOL_ENUM_VALUES, ARG_SCHEMAS, CONTENT_BLOCK_KEYS), tools/builtin-names.ts (BUILTIN_TOOL_NAMES),
the bundled agent names and pi-edit's EditError::KINDS. Dev-time only.
"""
import os
import re
import sys


def strings(body):
    return re.findall(r'"((?:[^"\\]|\\.)*)"', body)


def block(src, start_pat):
    """Text between the opening bracket after `start_pat` and its matching close."""
    m = re.search(start_pat, src)
    if not m:
        raise SystemExit(f"not found: {start_pat}")
    i = m.end() - 1
    opener = src[i]
    closer = {"{": "}", "[": "]", "(": ")"}[opener]
    depth = 0
    for j in range(i, len(src)):
        if src[j] == opener:
            depth += 1
        elif src[j] == closer:
            depth -= 1
            if depth == 0:
                return src[i + 1:j]
    raise SystemExit("unbalanced")


def c_list(name, items):
    out = [f"static const char *const {name}[] = {{"]
    line = "   "
    for it in items:
        s = ' "' + it + '",'
        if len(line) + len(s) > 110:
            out.append(line)
            line = "   "
        line += s
    out.append(line)
    out.append("    NULL,\n};")
    return "\n".join(out)


def main():
    root = sys.argv[1]
    an = open(os.path.join(root, "packages/coding-agent/src/session/session-anonymizer.ts"), encoding="utf-8").read()
    out = ["/* anon_tables.h - generated by build-tools/extract_anon_tables.py from omp's session-anonymizer.ts. */",
           "#ifndef OMC_ANON_TABLES_H", "#define OMC_ANON_TABLES_H", ""]

    # FIELD_RULES: fields("rule", [...]) groups and single `key: "rule"` lines
    rules = block(an, r"const FIELD_RULES: Record<string, Rule> = \{")
    pairs = []
    for m in re.finditer(r'\.\.\.fields\("(\w+)", \[(.*?)\]\)', rules, re.S):
        for k in strings(m.group(2)):
            pairs.append((k, m.group(1)))
    for m in re.finditer(r'^\t(\w+): "(\w+)",', rules, re.M):
        pairs.append((m.group(1), m.group(2)))
    out.append("static const char *const ANON_FIELD_RULES[][2] = {")
    for k, r in pairs:
        out.append(f'    {{"{k}", "{r}"}},')
    out.append("    {NULL, NULL},\n};\n")

    def rec_keys(var):
        body = block(an, r"const " + var + r": Record<string, true> = \{")
        keys = re.findall(r'^\t"?([\w.$-]+)"?: true', body, re.M)
        return keys

    for var, cname in [("TEXT_ARG_KEYS", "ANON_TEXT_ARG_KEYS"), ("PATH_KEYS", "ANON_PATH_KEYS"),
                       ("OPAQUE_ARG_KEYS", "ANON_OPAQUE_ARG_KEYS"), ("PATTERN_ARG_KEYS", "ANON_PATTERN_ARG_KEYS"),
                       ("TOOL_CALL_TYPES", "ANON_TOOL_CALL_TYPES"), ("KEEP_SEGMENTS", "ANON_KEEP_SEGMENTS"),
                       ("SUBCOMMANDS", "ANON_SUBCOMMANDS")]:
        out.append(c_list(cname, rec_keys(var)) + "\n")

    for var, cname in [("MIME_TYPES", "ANON_MIME_TYPES"), ("SHELL_COMMANDS", "ANON_SHELL_COMMANDS"),
                       ("COMMAND_PREFIXES", "ANON_COMMAND_PREFIXES"),
                       ("NUMERIC_FLAG_PROGRAMS", "ANON_NUMERIC_FLAG_PROGRAMS"), ("LONG_FLAGS", "ANON_LONG_FLAGS"),
                       ("ENV_NAMES", "ANON_ENV_NAMES"), ("KNOWN_SCHEMES", "ANON_KNOWN_SCHEMES"),
                       ("KNOWN_EXTENSIONS", "ANON_KNOWN_EXTENSIONS")]:
        body = block(an, r"const " + var + r"(?:: ReadonlySet<string>)? = new Set\(\[")
        out.append(c_list(cname, strings(body)) + "\n")

    # TOOL_ENUM_VALUES: key -> list (MIME_TYPES / editErrorKinds() referenced by name)
    body = block(an, r"const TOOL_ENUM_VALUES: Record<string, ReadonlySet<string>> = \{")
    kinds_src = open(os.path.join(root, "crates/pi-edit/src/error.rs"), encoding="utf-8").read()
    kinds = strings(block(kinds_src, r"pub const KINDS: &\[&str\] = &\["))
    mimes = strings(block(an, r"const MIME_TYPES: ReadonlySet<string> = new Set\(\["))
    out.append("/* key, then its values, NULL-terminated; the table ends with a NULL key */")
    out.append("static const char *const ANON_TOOL_ENUM_VALUES[] = {")
    for m in re.finditer(r'^\t(\w+): (new Set\(\[(.*?)\]\)|MIME_TYPES|new Set\(editErrorKinds\(\)\)),', body, re.M | re.S):
        key = m.group(1)
        if m.group(2) == "MIME_TYPES":
            vals = mimes
        elif "editErrorKinds" in m.group(2):
            vals = kinds
        else:
            vals = strings(m.group(3))
        out.append(f'    "{key}", ' + " ".join(f'"{v}",' for v in vals) + " NULL,")
    out.append("    NULL,\n};\n")

    # ARG_SCHEMAS: tool -> spec string
    body = block(an, r"const ARG_SCHEMAS: Record<string, ArgSchema> = \{")
    out.append("static const char *const ANON_ARG_SCHEMAS[][2] = {")
    for m in re.finditer(r'^\t(\w+): argSchema\(\s*"([^"]*)",?\s*\),', body, re.M | re.S):
        out.append(f'    {{"{m.group(1)}", "{m.group(2)}"}},')
    out.append("    {NULL, NULL},\n};\n")

    # CONTENT_BLOCK_KEYS: type -> keys
    body = block(an, r"const CONTENT_BLOCK_KEYS: Record<string, ReadonlySet<string>> = \{")
    out.append("static const char *const ANON_CONTENT_BLOCK_KEYS[] = {")
    for m in re.finditer(r'^\t(\w+): new Set\(\[(.*?)\]\),', body, re.M | re.S):
        out.append(f'    "{m.group(1)}", ' + " ".join(f'"{v}",' for v in strings(m.group(2))) + " NULL,")
    out.append("    NULL,\n};\n")

    names = open(os.path.join(root, "packages/coding-agent/src/tools/builtin-names.ts"), encoding="utf-8").read()
    out.append(c_list("ANON_BUILTIN_TOOLS", strings(block(names, r"export const BUILTIN_TOOL_NAMES = \["))) + "\n")

    agents = []
    adir = os.path.join(root, "packages/coding-agent/src/prompts/agents")
    agents_ts = open(os.path.join(root, "packages/coding-agent/src/task/agents.ts"), encoding="utf-8").read()
    for fn in re.findall(r'fileName: "([\w-]+\.md)"', agents_ts):
        p = os.path.join(adir, fn)
        if os.path.exists(p):
            m = re.search(r"^name: ([\w-]+)", open(p, encoding="utf-8").read(), re.M)
            if m:
                agents.append(m.group(1))
    for m in re.finditer(r'frontmatter: \{\s*name: "([\w-]+)"', agents_ts):
        agents.append(m.group(1))
    out.append(c_list("ANON_BUNDLED_AGENTS", agents) + "\n")
    out.append("#endif")
    print("\n".join(out))


if __name__ == "__main__":
    main()
